import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const directory = resolve(root, "packages/providers");
const target = resolve(root, "apps/agent/src/provider-manifest.ts");
const entries = [];
for (const item of (await readdir(directory, { withFileTypes: true })).sort(
  (a, b) => a.name.localeCompare(b.name),
)) {
  if (!item.isDirectory()) continue;
  const packageDir = resolve(directory, item.name);
  const pkg = JSON.parse(
    await readFile(resolve(packageDir, "package.json"), "utf8"),
  );
  if (!pkg.name?.startsWith("@sluice/provider-")) continue;
  const entry = pkg.exports?.["."];
  if (typeof entry !== "string" || !entry.startsWith("./")) {
    throw new Error(`${pkg.name} must export a local entry point`);
  }
  const entryPath = resolve(packageDir, entry);
  if (!entryPath.startsWith(packageDir + sep))
    throw new Error(`Invalid entry point for ${pkg.name}`);
  const path = relative(dirname(target), entryPath).split(sep).join("/");
  entries.push({
    name: pkg.name,
    path: path.startsWith(".") ? path : `./${path}`,
  });
}
const output = `// Generated by scripts/generate-providers.mjs. Do not edit.
import type { ProviderDefinition } from "@sluice/core";
import { z } from "zod";

const modules = ${JSON.stringify(entries, null, 2)} as const;
export const definitions: ProviderDefinition[] = [];
for (const entry of modules) {
  const module: { providerDefinition?: ProviderDefinition } = await import(new URL(entry.path, import.meta.url).href);
  const definition = module.providerDefinition;
  if (!definition || !/^[a-z][a-z0-9_-]{0,63}$/.test(definition.type) ||
      typeof definition.name !== "string" || !definition.name || definition.name.length > 100 ||
      typeof definition.implemented !== "boolean" || !(definition.configSchema instanceof z.ZodObject) ||
      typeof definition.create !== "function" || !definition.capabilities ||
      !Array.isArray(definition.capabilities.transports) ||
      definition.capabilities.transports.some((transport) => transport !== "tcp" && transport !== "udp") ||
      (definition.capabilities.readonly !== undefined && typeof definition.capabilities.readonly !== "boolean")) {
    throw new Error(\`Invalid provider definition in \${entry.name}\`);
  }
  if (definitions.some((item) => item.type === definition.type)) throw new Error(\`Duplicate provider type: \${definition.type}\`);
  definitions.push(definition);
}
`;
await writeFile(target, output);
